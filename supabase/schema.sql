-- Helper: invoice lines with the derived product/service label and a numeric rate.
create view demo.v_invoice_lines_enriched with (security_invoker = true) as
select
  l.*,
  coalesce(nullif(btrim(l.invoice_category), ''),
           nullif(btrim(l.service_type), ''),
           nullif(btrim(l.service_type_others), ''))            as product_service,
  case
    when nullif(btrim(l.invoice_category), '') is not null then 'Invoice Category'
    when coalesce(nullif(btrim(l.service_type), ''), nullif(btrim(l.service_type_others), '')) is not null
      then 'Service Type'
  end                                                           as product_service_type,
  coalesce(nullif(regexp_replace(coalesce(l.service_rate, ''), '[^0-9.]', '', 'g'), '')::numeric, 0) as rate_num
from demo.invoice_lines l;

-- Data Source tab: the worklist tasks as parsed from the site path.
create view analytics.v_quote_source_asset_tasks with (security_invoker = true) as
select t.task_did, t.org_name, t.project_name, t.asset_name, t.asset_id, t.task_name,
       t.subcon, t.gc, t.carrier, t.market, t.project, t.fuze_id
from demo.quote_tasks t;

-- Data Source tab: every invoicing-form line for those tasks, priced or not.
create view analytics.mv_quote_source_invoice_lines with (security_invoker = true) as
select l.task_did, t.asset_name, l.project, l.site_name, l.site_id, l.sow, l.pricing_type,
       l.service_type, l.service_type_others, l.service_rate, l.ll_cop, l.landlord,
       l.landlord_others, l.pmi_cop, l.rf_mitigation_cop,
       (l.rate_num > 0) as priced,
       l.form_did
from demo.v_invoice_lines_enriched l
join demo.quote_tasks t using (task_did);

-- Priced lines a user can choose between for a task.
create view analytics.mv_quote_invoice_options with (security_invoker = true) as
select l.task_did, l.line_key, l.product_service, l.product_service_type, l.service_rate,
       l.site_id, l.project, l.requirement_status, l.form_did
from demo.v_invoice_lines_enriched l
where l.rate_num > 0;

-- Base (pre-override) categories; only used for the distinct-value suggestions.
create view analytics.mv_quote_review with (security_invoker = true) as
select t.task_did, t.gc, t.carrier, t.market, t.project
from demo.quote_tasks t;

-- The main read model: one row per task.
create view analytics.v_quote_review with (security_invoker = true) as
with eff as (
  select
    t.task_did, t.asset_id, t.asset_name, t.task_name, t.task_status,
    -- override semantics: NULL = parsed value, '' = explicit blank, text = value
    case when o.subcon  is not null then nullif(o.subcon, '')  else t.subcon  end as subcon,
    case when o.gc      is not null then nullif(o.gc, '')      else t.gc      end as gc,
    case when o.carrier is not null then nullif(o.carrier, '') else t.carrier end as carrier,
    case when o.market  is not null then nullif(o.market, '')  else t.market  end as market,
    case when o.project is not null then nullif(o.project, '') else t.project end as project,
    case when o.fuze_id is not null then nullif(o.fuze_id, '') else t.fuze_id end as fuze_id,
    t.needs_review_base,
    coalesce(o.verified, false)                 as verified,
    o.verified_by, o.verified_at,
    (o.subcon  is not null)                     as subcon_overridden,
    (o.gc      is not null)                     as gc_overridden,
    (o.carrier is not null)                     as carrier_overridden,
    (o.market  is not null)                     as market_overridden,
    (o.project is not null)                     as project_overridden,
    (o.fuze_id is not null)                     as fuze_id_overridden,
    nullif(btrim(o.service_rate_override), '')    as service_rate_override,
    nullif(btrim(o.product_service_override), '') as product_service_override,
    o.chosen_line_key,
    case when jsonb_typeof(o.line_items) = 'array' and jsonb_array_length(o.line_items) > 0
         then o.line_items end                  as line_items,
    o.updated_by                                as override_by,
    o.updated_at                                as override_at
  from demo.quote_tasks t
  left join app_quote.overrides o using (task_did)
),
line_stats as (
  select task_did,
         count(*)                           as line_count,
         count(*) filter (where rate_num > 0) as priced_line_count
  from demo.v_invoice_lines_enriched
  group by task_did
),
picked as (
  -- The user's chosen priced line if it is still valid; otherwise the first
  -- priced line; otherwise the first unpriced line (for site/SOW context).
  select distinct on (e.task_did)
    e.task_did,
    l.line_key, l.project, l.site_name, l.site_id, l.product_service, l.product_service_type,
    l.invoice_category, l.service_type, l.sow, l.service_rate, l.rate_num,
    l.requirement_status, l.form_did,
    (l.line_key = e.chosen_line_key and l.rate_num > 0) as is_chosen
  from eff e
  join demo.v_invoice_lines_enriched l using (task_did)
  order by e.task_did,
           (l.line_key = e.chosen_line_key and l.rate_num > 0) desc,
           (l.rate_num > 0) desc,
           l.line_key
),
dir as (
  select match_key,
         string_agg(distinct nullif(btrim(recipient), ''), ', ') as recipient,
         string_agg(distinct nullif(btrim(cc), ''), ', ')        as cc,
         count(distinct (coalesce(btrim(recipient), '') || '|' || coalesce(btrim(cc), ''))) > 1 as conflict
  from reference.ref_quote_directory
  where match_key is not null
  group by match_key
)
select
  e.task_did, e.asset_id, e.asset_name, e.task_name, e.task_status,
  e.subcon, e.gc, e.carrier, e.market, e.project, e.fuze_id,
  (e.needs_review_base and not e.verified)        as needs_review,
  e.needs_review_base,
  e.verified, e.verified_by, e.verified_at,
  e.subcon_overridden, e.gc_overridden, e.carrier_overridden,
  e.market_overridden, e.project_overridden, e.fuze_id_overridden,
  (e.service_rate_override is not null)           as service_rate_overridden,
  (e.product_service_override is not null)        as product_service_overridden,
  e.override_by, e.override_at,
  p.project                                       as inv_project,
  p.site_name                                     as inv_site_name,
  p.site_id                                       as inv_site_id,
  coalesce(e.product_service_override, p.product_service) as inv_product_service,
  p.product_service_type                          as inv_product_service_type,
  p.invoice_category                              as inv_invoice_category,
  p.service_type                                  as inv_service_type,
  p.sow                                           as inv_sow,
  coalesce(e.service_rate_override,
           case when p.rate_num > 0 then p.service_rate end) as inv_service_rate,
  p.requirement_status                            as inv_requirement_status,
  p.form_did                                      as inv_form_did,
  e.chosen_line_key,
  coalesce(p.is_chosen, false)                    as invoice_chosen,
  d.recipient                                     as quote_recipient,
  d.cc                                            as quote_cc,
  (d.match_key is not null)                       as directory_matched,
  coalesce(d.conflict, false)                     as directory_conflict,
  coalesce(s.priced_line_count, 0)::int           as priced_line_count,
  case
    when coalesce(s.line_count, 0) = 0 then 'no_match'
    when coalesce(p.rate_num, 0) > 0
      or coalesce(nullif(regexp_replace(coalesce(e.service_rate_override, ''), '[^0-9.]', '', 'g'), '')::numeric, 0) > 0
      then 'ready'
    else 'no_price'
  end                                             as status,
  e.line_items
from eff e
left join line_stats s using (task_did)
left join picked p using (task_did)
left join dir d
  on d.match_key =
     upper(regexp_replace(btrim(coalesce(e.gc, '')),      '\s+', ' ', 'g')) || '|' ||
     upper(regexp_replace(btrim(coalesce(e.carrier, '')), '\s+', ' ', 'g')) || '|' ||
     upper(regexp_replace(btrim(coalesce(e.market, '')),  '\s+', ' ', 'g')) || '|' ||
     upper(regexp_replace(btrim(coalesce(e.project, '')), '\s+', ' ', 'g'));

