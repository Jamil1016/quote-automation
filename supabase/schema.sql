  on app_quote.send_identities (owner_email, email) where scope = 'personal';

-- -----------------------------------------------------------------------------
-- RPC: claim due emails exactly once.
-- Stamps claimed_at under FOR UPDATE SKIP LOCKED and returns only the rows THIS
-- call took, so two overlapping dispatcher runs can never send the same draft.
-- status stays 'scheduled' while claimed; the dispatcher then marks each row
-- sent / failed / cancelled, and frees stale claims (claimed_at older than 5 min).
-- -----------------------------------------------------------------------------
create or replace function app_quote.claim_due_emails(p_limit integer default 50)
returns setof app_quote.email_queue
language sql
volatile
set search_path = ''
as $$
  update app_quote.email_queue q
     set claimed_at = now()
   where q.id in (
           select c.id
             from app_quote.email_queue c
            where c.status = 'scheduled'
              and c.returned_at is null
              and c.claimed_at is null
              and c.scheduled_at <= now()
            order by c.scheduled_at, c.id
            limit greatest(coalesce(p_limit, 50), 0)
              for update skip locked
         )
  returning q.*;
$$;

