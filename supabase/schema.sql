-- =============================================================================
-- Quote Automation: database schema for the public demo
-- =============================================================================
-- HOW TO APPLY
--   Option A (Supabase dashboard): SQL Editor -> paste this whole file -> Run.
--   Option B (psql):  psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -f supabase/schema.sql
--   Then run supabase/seed.sql the same way.
--
-- REQUIRED API SETTING (the app cannot read anything until this is done)
--   Dashboard -> Project Settings -> API (Data API) -> "Exposed schemas":
--   add  analytics, data_staging, reference, app_quote  (keep public). Save.
--
-- WHAT THIS FILE CREATES
--   app_quote.*       working tables the app reads and writes (8 tables + 1 RPC)
--   reference.*       the quote directory (who receives each quote)
--   data_staging.*    two stub tables that only carry a "last refreshed" time
--   demo.*            flat base tables that stand in for the upstream pipeline
--   analytics.*       the read model (5 views) built over demo.* + app_quote.*
--
-- In the internal version the analytics objects are materialized views fed by a
-- data pipeline. Here they are plain views over two flat demo tables, keeping
-- the same names and columns so the application code is unchanged.
--
-- SECURITY POSTURE
--   Every server-side call uses the service-role key. RLS is enabled on every
--   table with NO policies, and no schema is granted to anon/authenticated, so
--   the browser (anon key) can read nothing. The only browser-side Supabase
--   feature used is a Realtime Presence channel, which needs no table.
--
-- The file is idempotent: it can be re-run safely. Views are dropped and
-- recreated; tables use CREATE TABLE IF NOT EXISTS and keep their data.
-- =============================================================================

create schema if not exists analytics;
create schema if not exists data_staging;
create schema if not exists reference;
create schema if not exists app_quote;
create schema if not exists demo;

-- -----------------------------------------------------------------------------
-- reference.ref_quote_directory: (gc, carrier, market, project) -> recipients
-- -----------------------------------------------------------------------------
create table if not exists reference.ref_quote_directory (
  id         bigint generated by default as identity primary key,
  gc         text,
  carrier    text,
  market     text,
  project    text,
  recipient  text,          -- comma-separated To addresses
  cc         text,          -- comma-separated Cc addresses
  textjoin   text,          -- "gc_carrier_market_project" (display aid)
  -- Normalised join key, written by the app (lib/quotes/actions.ts normPart):
  -- trim, collapse whitespace, upper-case, joined with "|".
  match_key  text
);
create index if not exists ref_quote_directory_match_key_idx
  on reference.ref_quote_directory (match_key);

